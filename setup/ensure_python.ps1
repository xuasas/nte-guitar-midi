# Locate a compatible interpreter, or download the official portable CPython
# distribution into this project. No global installation or PATH changes.
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
$Root = Split-Path -Parent $PSScriptRoot
$RuntimeRoot = Join-Path $Root 'runtime'
$Runtime = Join-Path $RuntimeRoot 'python311'
$RuntimePy = Join-Path $Runtime 'python.exe'
$BundleUrl = 'https://www.python.org/ftp/python/3.11.9/python-3.11.9-amd64.zip'
# CPython's official Windows install-manager metadata, windows-3.11.9.json.
$BundleSha256 = '4BA90A4AB8990891033D37FF04D2047FDAE8948D0D2729A68D3A6A17C585B681'

function Test-CompatiblePython([string]$Exe, [string[]]$PythonArgs = @()) {
    $old = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $null = & $Exe @PythonArgs -c 'import sys,struct,venv,ensurepip; sys.exit(0 if sys.version_info[:2] == (3,11) and struct.calcsize(chr(80)) == 8 else 1)' 2>$null
        return ($LASTEXITCODE -eq 0)
    } catch { return $false } finally { $ErrorActionPreference = $old }
}

if (Test-Path -LiteralPath $RuntimePy) {
    if (-not (Test-CompatiblePython $RuntimePy)) { throw 'The project Python runtime is incomplete. Repair or remove runtime/python311 and retry.' }
    Write-Host '[python] project Python 3.11 x64 is ready.'
    exit 0
}
$launcher = Get-Command py.exe -ErrorAction SilentlyContinue
if ($launcher -and (Test-CompatiblePython $launcher.Source @('-3.11-64'))) {
    Write-Host '[python] existing Python 3.11 x64 found.'
    exit 0
}
$python = Get-Command python.exe -ErrorAction SilentlyContinue
if ($python -and ($python.Source -notmatch '[\\/]WindowsApps[\\/]') -and (Test-CompatiblePython $python.Source)) {
    Write-Host '[python] existing Python 3.11 x64 found.'
    exit 0
}
if (-not [Environment]::Is64BitOperatingSystem) { throw '64-bit Windows is required for the CPU transcription model.' }
if (Test-Path -LiteralPath $Runtime) { throw 'runtime/python311 already exists but is incomplete. Please inspect it before retrying.' }

New-Item -ItemType Directory -Path $RuntimeRoot -Force | Out-Null
$nonce = [Guid]::NewGuid().ToString('N')
$zip = Join-Path $RuntimeRoot ('python311-' + $nonce + '.zip')
$staging = Join-Path $RuntimeRoot ('python311-' + $nonce + '.staging')
try {
    Write-Host '[python] downloading official Python 3.11.9 x64 (about 32 MB)...'
    [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
    Invoke-WebRequest -Uri $BundleUrl -OutFile $zip -UseBasicParsing
    $actual = (Get-FileHash -LiteralPath $zip -Algorithm SHA256).Hash
    if ($actual -ne $BundleSha256) { throw 'Python download checksum did not match; please retry on a trusted network.' }
    Expand-Archive -LiteralPath $zip -DestinationPath $staging
    if (-not (Test-CompatiblePython (Join-Path $staging 'python.exe'))) { throw 'The downloaded Python runtime failed its self-check.' }
    if (Test-Path -LiteralPath $Runtime) { throw 'The runtime folder was created concurrently; stopping without overwriting it.' }
    Move-Item -LiteralPath $staging -Destination $Runtime
    Write-Host '[python] project-local Python 3.11.9 x64 is ready.'
} finally {
    if (Test-Path -LiteralPath $zip) { Remove-Item -LiteralPath $zip -Force -ErrorAction SilentlyContinue }
    # The staging path was generated by this invocation under the known runtime root.
    if (Test-Path -LiteralPath $staging) {
        $resolvedStage = (Resolve-Path -LiteralPath $staging).Path
        $resolvedRoot = (Resolve-Path -LiteralPath $RuntimeRoot).Path.TrimEnd('\')
        if ($resolvedStage.StartsWith($resolvedRoot + '\python311-', [StringComparison]::OrdinalIgnoreCase) -and
            -not ((Get-Item -LiteralPath $resolvedStage -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)) {
            Remove-Item -LiteralPath $resolvedStage -Recurse -Force -ErrorAction SilentlyContinue
        }
    }
}
